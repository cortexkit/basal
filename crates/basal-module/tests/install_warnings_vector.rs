//! The `flow.install_request` basal sends core for a flow whose root lies in
//! a folder both macOS and Windows protect, pinned in
//! test-vectors/install-warnings-v1 so core can check its parsing against it.
//!
//! Install refuses a root that does not exist, and the vector's root must be
//! spelled `~/Documents/notes`. So this binary points `HOME` at a scratch
//! folder holding `Documents/notes` instead of touching the real home folder.
//! It is its own test binary, with this one test, because changing the
//! environment is only sound while no other thread reads it. Windows expands
//! `~` to the process profile rather than `HOME`, so it is not built there.
#![cfg(not(windows))]

mod common;
mod wire;

use std::sync::Arc;

use basal_core::NoHooks;
use basal_host::core_consent::CoreConsent;
use basal_host::core_host::CoreHost;
use basal_host::routing::{ModuleOpsHost, RoutingHost};
use basal_host::subc_catalog::SubcCatalog;
use basal_module::caller::Caller;
use basal_module::module::Hosts;
use basal_module::unconfigured::UnconfiguredHost;
use serde_json::{Value, json};
use sha2::{Digest, Sha256};
use wire::Fake;

const DIRECTORY: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../test-vectors/install-warnings-v1"
);
const FILE: &str = "protected-root.json";

/// A synthetic flow: its only notable grant is an `fs.read` root under
/// `~/Documents`, which macOS and Windows both protect.
fn protected_root_manifest() -> Value {
    json!({
        "id": "protected-root-sample",
        "version": 1,
        "purpose": "Sample flow reading notes under a protected folder",
        "trigger": {"schedule": {"interval": "1h"}},
        "sinks": [{"agent": "SYNAPSE", "digest_max": "piggyback"}],
        "fs": {"read": ["~/Documents/notes"]},
    })
}

/// Basal's production hosts, with core's side played by the wire fake.
fn hosts(fake: Arc<Fake>) -> Hosts {
    let catalog = Arc::new(SubcCatalog::new(fake.clone()));
    Hosts {
        transport: Arc::new(basal_module::unconfigured::UnconfiguredTransport),
        host: Arc::new(RoutingHost::new(
            Arc::new(ModuleOpsHost::new(fake.clone(), catalog.clone())),
            Arc::new(CoreHost::new(fake.clone())),
            Arc::new(UnconfiguredHost::new()),
        )),
        catalog,
        consent: Arc::new(CoreConsent::new(fake)),
        hooks: Arc::new(NoHooks),
    }
}

/// With `BASAL_WRITE_VECTORS` set the test writes the vector and its checksums
/// and fails, requiring a separate run to verify the regenerated files.
#[test]
fn protected_root_install_request_vector_matches_what_basal_sends_core() {
    let home = common::scratch("protected-root-vector-home");
    std::fs::create_dir_all(home.join("Documents/notes")).expect("create the vector's root");
    // SAFETY: this binary holds only this test, and nothing else has started
    // a thread that reads the environment yet.
    unsafe { std::env::set_var("HOME", &home) };

    let fake = Fake::new();
    // No schedule fire is replayed, so the dry run needs no worker and its
    // summary depends only on the fixture's fixed clock.
    let f = common::fixture(
        "protected-root-vector",
        common::Options {
            hosts: Some(hosts(fake.clone())),
            dry_run_max_fires: Some(0),
            ..common::Options::default()
        },
    );
    let reply = common::install(
        &f,
        &Caller::Operator,
        "return 1;\n",
        &protected_root_manifest(),
    );
    assert_eq!(reply["state"], "pending", "the warning is not a refusal");

    let calls = fake.calls("flow.install_request");
    assert_eq!(calls.len(), 1);
    let request = calls[0]["params"].clone();
    assert_eq!(
        request["flow_install"]["warnings"],
        json!([{
            "code": "protected_root",
            "detail": "On macOS, the first access to ~/Documents asks the operator for permission.\n\
                       On Windows, writes under ~/Documents are blocked while Controlled Folder Access is on.",
        }]),
    );

    let bytes = (serde_json::to_string_pretty(&request).expect("pretty JSON") + "\n").into_bytes();
    let readme = std::fs::read(format!("{DIRECTORY}/README.md")).expect("vector README");
    let sums = format!(
        "{}  README.md\n{}  {FILE}\n",
        basal_proto::util::hex(&Sha256::digest(&readme)),
        basal_proto::util::hex(&Sha256::digest(&bytes)),
    );
    if std::env::var_os("BASAL_WRITE_VECTORS").is_some() {
        std::fs::write(format!("{DIRECTORY}/{FILE}"), &bytes).expect("write vector");
        std::fs::write(format!("{DIRECTORY}/SHA256SUMS"), &sums).expect("write checksums");
        drop(f);
        let _ = std::fs::remove_dir_all(&home);
        panic!("vectors rewritten, rerun without the variable");
    }
    let committed = std::fs::read(format!("{DIRECTORY}/{FILE}")).unwrap_or_default();
    assert!(
        committed == bytes,
        "{FILE} differs from what basal sends; generated bytes:\n{}",
        String::from_utf8_lossy(&bytes)
    );
    let committed_sums =
        std::fs::read_to_string(format!("{DIRECTORY}/SHA256SUMS")).unwrap_or_default();
    assert_eq!(
        committed_sums, sums,
        "SHA256SUMS differs from the generated bytes"
    );
    drop(f);
    let _ = std::fs::remove_dir_all(&home);
}
